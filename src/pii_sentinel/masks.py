"""Masking rules per PII type, as SQL for Snowflake masking policies / Databricks Unity Catalog column masks,
plus the same rule in Python for previews in the report (so raw values never appear in output)."""
from __future__ import annotations

import re

# kind: how the value is masked.  keep_last4 suits identifiers people confirm by their last digits.
RULES = {
    "aadhaar": "keep_last4", "card": "keep_last4", "phone_in": "keep_last4",
    "email": "email", "upi": "email",
    "pan": "full", "passport_in": "full", "gstin": "full", "dob": "full",
    "person_name": "full", "address": "full", "ip": "full", "ifsc": "none",
}


def preview(pii: str, value: str) -> str:
    rule = RULES.get(pii, "full")
    if rule == "keep_last4":
        digits = re.sub(r"\D", "", value)
        return "X" * max(0, len(digits) - 4) + digits[-4:]
    if rule == "email" and "@" in value:
        local, domain = value.split("@", 1)
        return (local[:1] + "***@" + domain) if local else "***@" + domain
    if rule == "none":
        return value
    return "*****"


def _sql_expr(pii: str, dialect: str) -> str:
    rule = RULES.get(pii, "full")
    if rule == "keep_last4":
        digits = "REGEXP_REPLACE(val, '[^0-9]', '')"  # both engines replace every match by default
        expr = f"CONCAT(REPEAT('X', GREATEST(LENGTH({digits}) - 4, 0)), RIGHT({digits}, 4))"
        return expr if dialect == "snowflake" else expr.lower().replace("'x'", "'X'")
    if rule == "email":
        if dialect == "snowflake":
            return "CONCAT(LEFT(val, 1), '***@', SPLIT_PART(val, '@', 2))"
        return "concat(left(val, 1), '***@', split_part(val, '@', 2))"
    if rule == "none":
        return "val"
    return "'*****'"


def snowflake_policies(findings, reader_role: str = "PII_READER") -> str:
    lines = ["-- Generated by pii-sentinel. Review before applying.",
             "CREATE TAG IF NOT EXISTS pii_type;", ""]
    for pii in sorted({f.pii for f in findings if RULES.get(f.pii) != "none"}):
        lines += [f"CREATE MASKING POLICY IF NOT EXISTS pii_mask_{pii} AS (val STRING) RETURNS STRING ->",
                  f"  CASE WHEN IS_ROLE_IN_SESSION('{reader_role}') THEN val ELSE {_sql_expr(pii, 'snowflake')} END;", ""]
    for f in findings:
        lines.append(f"ALTER TABLE {f.table} MODIFY COLUMN {f.column} SET TAG pii_type = '{f.pii}';")
        if RULES.get(f.pii) != "none":
            lines.append(f"ALTER TABLE {f.table} MODIFY COLUMN {f.column} SET MASKING POLICY pii_mask_{f.pii};"
                         + ("  -- column is not STRING: cast or use a typed policy" if f.pii == "dob" else ""))
    return "\n".join(lines) + "\n"


def databricks_masks(findings, reader_group: str = "pii_readers", schema: str = "governance") -> str:
    lines = ["-- Generated by pii-sentinel. Review before applying (Unity Catalog).", ""]
    for pii in sorted({f.pii for f in findings if RULES.get(f.pii) != "none"}):
        lines += [f"CREATE FUNCTION IF NOT EXISTS {schema}.mask_{pii}(val STRING) RETURN",
                  f"  CASE WHEN is_account_group_member('{reader_group}') THEN val ELSE {_sql_expr(pii, 'databricks')} END;", ""]
    for f in findings:
        lines.append(f"ALTER TABLE {f.table} ALTER COLUMN {f.column} SET TAGS ('pii_type' = '{f.pii}');")
        if RULES.get(f.pii) != "none":
            lines.append(f"ALTER TABLE {f.table} ALTER COLUMN {f.column} SET MASK {schema}.mask_{f.pii};")
    return "\n".join(lines) + "\n"
